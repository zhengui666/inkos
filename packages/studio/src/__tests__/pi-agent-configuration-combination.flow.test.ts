describe("actual Studio Pi dispatcher and durable request history (offline native transport)", () => {
  it("freezes the running Pi request after saving Codex, then records the next actual Codex run separately", async () => {
    let nextCodexRevision = -1;
    const codex = new CodexFixture(() => {
      const context = currentCodexRun(); if (!context) throw new Error("Expected actual Codex admission");
      nextCodexRevision = context.selection.configRevision;
      return { text: JSON.stringify({ status: "answered", message: "Next actual Codex answer" }) };
    });
    const fixture = await studio("valid", codex), sessionId = await fixture.session(), gate = hold();
    let piRevision = -1;
    const network = vi.fn(async (input: string | URL | Request, init?: RequestInit) => {
      expect(urlOf(input)).toBe("https://api.openai.com/v1/responses");
      expect((init?.method ?? (input instanceof Request ? input.method : "GET")).toUpperCase()).toBe("POST");
      const context = currentRuntimeRun(); if (context?.harnessId !== "pi") throw new Error("Expected actual Pi admission");
      piRevision = context.selection.configRevision; gate.enter(); await waitForResponse(gate, init?.signal);
      return rawResponse("Frozen actual Pi answer", "offline-pi-first-response");
    });
    vi.stubGlobal("fetch", network);
    const first = run(fixture, sessionId, "Answer with the current Pi configuration");
    await gate.entered;
    const admitted = await readAgentSettings(fixture.root);
    expect(admitted).toMatchObject({ selectedHarnessId: "pi", revision: piRevision });
    expect(admitted.modelConnectionRef).not.toBeNull(); expect(createCodexClient).not.toHaveBeenCalled();
    const saved = await saveHarness(fixture, "codex");
    expect(saved).toMatchObject({ selectedHarnessId: "codex", revision: piRevision + 1, modelConnectionRef: null });
    gate.release(); const firstResponse = await first;
    expect(firstResponse.status, await firstResponse.clone().text()).toBe(200);
    expect((await firstResponse.json()).response).toBe("Frozen actual Pi answer");
    expect(network).toHaveBeenCalledOnce(); expect(createCodexClient).not.toHaveBeenCalled(); expect(codex.requests).toEqual([]);
    const recordedPi = await history(fixture.root, sessionId);
    expect(recordedPi.projected.issues).toEqual([]); expect(recordedPi.projected.requests).toHaveLength(1);
    const pi = recordedPi.projected.requests[0]!;
    expect(pi).toMatchObject({ transcriptStatus: "committed", episodeStatus: "completed", recording: "recorded",
      selection: { saved: { harnessId: "pi", revision: piRevision, model: null, effort: null, speed: null },
        selection: { harnessId: "pi", configRevision: piRevision, modelId: "gpt-5.4", effort: "low", serviceTier: null } } });
    expect(pi.dispatches).toHaveLength(1); expect(pi.dispatches[0]).toMatchObject({ operation: "pi-prompt", agentRole: "main",
      piSessionId: expect.any(String), wire: { model: "gpt-5.4", effort: "low", serviceTier: null } });
    // Restored real SDK sessions persist a thinking entry, not a model-change
    // entry. A selected/requested model is not an observed native model fact.
    expect(pi.observations).toHaveLength(1);
    expect(pi.observations.every(observation => observation.source === "pi-session-entry" && observation.linked)).toBe(true);
    expect(pi.observations[0]).toMatchObject({ effective: { effort: "low" }, fields: { modelId: { state: "unknown" }, effort: { state: "observed", value: "low" } } });
    expect(recordedPi.events.filter(event => event.type === RUN_HISTORY_EVENT_TYPE).length).toBeGreaterThanOrEqual(3);
    expectNoPrivateHistory(recordedPi.projected);

    const second = await run(fixture, sessionId, "Answer with the newly saved Codex configuration");
    expect(second.status, await second.clone().text()).toBe(200); expect((await second.json()).response).toBe("Next actual Codex answer");
    expect(createCodexClient).toHaveBeenCalled(); expect(codex.turns).toHaveLength(1); expect(network).toHaveBeenCalledOnce();
    const finalSettings = await readAgentSettings(fixture.root), recorded = await history(fixture.root, sessionId);
    expect(finalSettings.selectedHarnessId).toBe("codex"); expect(finalSettings.revision).toBe(nextCodexRevision);
    expect(nextCodexRevision).toBeGreaterThan(saved.revision);
    expect(recorded.projected.issues).toEqual([]); expect(recorded.projected.requests).toHaveLength(2);
    expect(recorded.projected.requests[0]).toEqual(pi);
    expect(recorded.projected.requests[1]).toMatchObject({ transcriptStatus: "committed", recording: "recorded",
      selection: { saved: { harnessId: "codex", revision: nextCodexRevision }, selection: { harnessId: "codex", configRevision: nextCodexRevision } } });
    expect(recorded.projected.requests[1]!.dispatches.map(dispatch => dispatch.operation)).toEqual(["codex-thread-start", "codex-turn-start"]);
    expectNoPrivateHistory(recorded.projected);
    const restored = await (await fixture.app.request(`/api/v1/sessions/${sessionId}`)).json();
    expect(restored.chatRequest.status).toBe("completed");
    expect(restored.session.messages.filter((message: { content: string }) =>
      ["Frozen actual Pi answer", "Next actual Codex answer"].includes(message.content))).toHaveLength(2);
  }, 30_000);

  it.each(["missing", "invalid"] as const)("rejects %s native Pi credentials through the actual caller without creating an owner or using Codex", async auth => {
    const fixture = await studio(auth), sessionId = await fixture.session();
    const network = vi.mocked(fetch);
    const response = await run(fixture, sessionId, "Use Pi without a verified OAuth credential");
    expect(response.status, await response.clone().text()).toBe(500);
    const failure = await response.json();
    expect(failure.error).toMatchObject({ code: "INKOS_ACTION_ERROR", message: expect.stringContaining(auth === "missing"
      ? "Pi requires an existing ChatGPT OAuth credential" : "Cannot verify the Pi ChatGPT OAuth credential") });
    expect(network).not.toHaveBeenCalled(); expect(createCodexClient).not.toHaveBeenCalled();
    await expect(access(join(fixture.agentDir, "inkos-connection.json"))).rejects.toMatchObject({ code: "ENOENT" });
    const settings = await readAgentSettings(fixture.root);
    expect(settings).toMatchObject({ selectedHarnessId: "pi", modelConnectionRef: null });
    const durable = await history(fixture.root, sessionId);
    expect(durable.transcript.some(event => event.type === "request_committed")).toBe(false);
    expect(durable.episodes).toEqual([]); expect(durable.projected.requests).toEqual([]);
    const restored = await (await fixture.app.request(`/api/v1/sessions/${sessionId}`)).json();
    expect(restored.chatRequest).toMatchObject({ status: "failed", error: { code: "INKOS_ACTION_ERROR" } });
    expect(JSON.stringify(failure)).not.toContain("synthetic-invalid-access");
  }, 30_000);

  it("rejects an OAuth replacement during actual Pi streaming and retains failed Pi evidence without a Codex fallback", async () => {
    const fixture = await studio(), sessionId = await fixture.session(), gate = hold();
    const network = vi.fn(async (input: string | URL | Request, init?: RequestInit) => {
      expect(urlOf(input)).toBe("https://api.openai.com/v1/responses");
      gate.enter(); await waitForResponse(gate, init?.signal);
      return rawResponse("Unaccepted candidate after OAuth replacement", "offline-replaced-response");
    });
    vi.stubGlobal("fetch", network);
    const response = run(fixture, sessionId, "Answer while Pi is admitted"); await gate.entered;
    const ownerPath = join(fixture.agentDir, "inkos-connection.json"), before = JSON.parse(await readFile(ownerPath, "utf8"));
    expect(before).toMatchObject({ harnessId: "pi", localState: "ready", authGeneration: 1 });
    // External credential replacement is a native input mutation, not a fake
    // owner version or a hand-written execution/transcript/history receipt.
    await writeFile(join(fixture.agentDir, "auth.json"), JSON.stringify({ openai: credential("external-replacement") }));
    gate.release(); const failed = await response;
    expect(failed.status, await failed.clone().text()).toBe(500);
    expect(await failed.json()).toMatchObject({ error: { code: "INKOS_ACTION_ERROR", message: expect.stringContaining("Pi OAuth credential continuity changed") } });
    expect(network).toHaveBeenCalledOnce(); expect(createCodexClient).not.toHaveBeenCalled();
    const after = JSON.parse(await readFile(ownerPath, "utf8"));
    expect(after).toMatchObject({ localState: "unknown", authGeneration: before.authGeneration + 1, connectionRef: before.connectionRef });
    const durable = await history(fixture.root, sessionId);
    expect(durable.projected.issues).toEqual([]); expect(durable.projected.requests).toHaveLength(1);
    expect(durable.projected.requests[0]).toMatchObject({ transcriptStatus: "failed", recording: "recorded",
      selection: { selection: { harnessId: "pi", authGeneration: before.authGeneration } } });
    expect(durable.projected.requests[0]!.dispatches.map(dispatch => dispatch.operation)).toEqual(["pi-prompt"]);
    expect(durable.transcript.at(-1)?.type).toBe("request_failed");
    expect(durable.transcript.some(event => event.type === "request_committed")).toBe(false);
    expectNoPrivateHistory(durable.projected);
    const restored = await (await fixture.app.request(`/api/v1/sessions/${sessionId}`)).json();
    expect(restored.chatRequest.status).toBe("failed");
    expect(restored.session.messages.some((message: { content: string }) => message.content === "Unaccepted candidate after OAuth replacement")).toBe(false);
  }, 30_000);

  it("keeps a real native refresh pending through Stop, rejects duplicate chat, then drains the failed refresh without dispatching Responses or Codex", async () => {
    const fixture = await studio("expired"), sessionId = await fixture.session(), gate = hold();
    const network = vi.fn(async (input: string | URL | Request, init?: RequestInit) => {
      // This is only the official SDK's refresh transport response; neither
      // OAuth derivation, native modify nor owner/drain is replaced by a shim.
      // openaiProvider loads openai-chatgpt (direct Responses token sharing),
      // not the separate openai-codex provider/OAuth/backend-api protocol.
      expect(urlOf(input)).toBe("https://auth.openai.com/api/accounts/oauth/token");
      expect((init?.method ?? (input instanceof Request ? input.method : "GET")).toUpperCase()).toBe("POST");
      const params = new URLSearchParams(String(init?.body));
      expect(params.get("grant_type")).toBe("refresh_token");
      expect(params.has("refresh_token")).toBe(true); expect(params.has("client_id")).toBe(true);
      expect(params.get("resource")).toBe("https://api.openai.com/v1");
      gate.enter();
      // Native saving belongs to the owner even when getAuth is cancelled.
      // Keep that actual external request alive until its explicit completion.
      await gate.wait;
      return new Response(JSON.stringify({ error: "invalid_grant", error_description: "Offline fixture declines refresh" }),
        { status: 401, headers: { "content-type": "application/json" } });
    });
    vi.stubGlobal("fetch", network);
    let settled = false;
    const running = run(fixture, sessionId, "Answer while native OAuth requires refresh");
    void running.then(() => { settled = true; }, () => { settled = true; });
    await gate.entered;
    const ownerPath = join(fixture.agentDir, "inkos-connection.json");
    const pendingBytes = await readFile(ownerPath, "utf8"), before = JSON.parse(pendingBytes);
    expect(before).toMatchObject({ harnessId: "pi", localState: "ready", authGeneration: 1,
      pendingRefresh: { operationId: expect.any(String), authGeneration: 1 } });
    expect(settled).toBe(false); expect(network).toHaveBeenCalledOnce(); expect(createCodexClient).not.toHaveBeenCalled();
    const observation = await fixture.app.request("/api/v1/agent-configuration/harnesses/pi/state");
    expect(observation.status).toBe(200);
    expect(await observation.json()).toMatchObject({ state: { harnessId: "pi", availability: "available",
      localAuthentication: "unknown", catalog: null, execution: null } });
    expect(await readFile(ownerPath, "utf8")).toBe(pendingBytes);
    expect(network).toHaveBeenCalledOnce(); expect(settled).toBe(false);

    const duplicate = await run(fixture, sessionId, "Do not create another request while refresh is pending");
    expect(duplicate.status).toBe(409);
    expect(await duplicate.json()).toMatchObject({ error: { code: "CHAT_REQUEST_ALREADY_RUNNING" }, chatRequest: { status: "running" } });
    const stop = await fixture.app.request(`/api/v1/sessions/${sessionId}/abort?scope=chat`, post({}));
    expect(stop.status).toBe(200); expect(await stop.json()).toEqual({ ok: true, aborted: true });
    expect(settled).toBe(false);
    const stopping = await (await fixture.app.request(`/api/v1/sessions/${sessionId}`)).json();
    expect(stopping.chatRequest).toMatchObject({ status: "running", cancelRequestedAt: expect.any(Number) });
    expect(JSON.parse(await readFile(ownerPath, "utf8"))).toMatchObject({ pendingRefresh: before.pendingRefresh });
    gate.release(); const failed = await running;
    expect(failed.status, await failed.clone().text()).toBe(500);
    expect(await failed.json()).toMatchObject({ error: { code: "INKOS_ACTION_ERROR" } });
    expect(network).toHaveBeenCalledOnce(); expect(createCodexClient).not.toHaveBeenCalled();
    const after = JSON.parse(await readFile(ownerPath, "utf8"));
    expect(after).toMatchObject({ localState: "unknown", authGeneration: before.authGeneration + 1, connectionRef: before.connectionRef });
    expect(after).not.toHaveProperty("pendingRefresh");
    const durable = await history(fixture.root, sessionId);
    expect(durable.projected.issues).toEqual([]); expect(durable.projected.requests).toHaveLength(1);
    expect(durable.projected.requests[0]).toMatchObject({ transcriptStatus: "failed", episodeStatus: "cancelled", recording: "recorded",
      selection: { selection: { harnessId: "pi", authGeneration: before.authGeneration } } });
    expect(durable.projected.requests[0]!.dispatches.map(dispatch => dispatch.operation)).toEqual(["pi-prompt"]);
    expect(durable.transcript.at(-1)?.type).toBe("request_failed");
    expect(durable.transcript.some(event => event.type === "request_committed")).toBe(false);
    expectNoPrivateHistory(durable.projected);
    const stopped = await (await fixture.app.request(`/api/v1/sessions/${sessionId}`)).json();
    expect(stopped.chatRequest).toMatchObject({ status: "cancelled", cancelRequestedAt: expect.any(Number) });
    // The existing ChatRequestStore deliberately clears retry/error on a
    // durable user cancellation; failure evidence stays in the transcript.
    expect(stopped.chatRequest.retry).toBeUndefined(); expect(stopped.chatRequest.error).toBeUndefined();
    expect((await readAgentSettings(fixture.root)).selectedHarnessId).toBe("pi");
  }, 30_000);
});
