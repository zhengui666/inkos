const credential = (suffix = "first", expires = Date.now() + 3_600_000) => ({
  type: "oauth", access: `synthetic-pi-access-${suffix}`, refresh: `synthetic-pi-refresh-${suffix}`, expires,
  clientId: "synthetic-offline-pi-client", scopes: ["chatgpt.tokens.use.direct"],
});
const post = (body: unknown): RequestInit => ({ method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
function hold() {
  let enter!: () => void, release!: () => void;
  const entered = new Promise<void>(resolve => { enter = resolve; });
  const wait = new Promise<void>(resolve => { release = resolve; });
  releases.push(release);
  return { entered, enter, release, wait };
}
function urlOf(input: string | URL | Request): string { return input instanceof Request ? input.url : String(input); }
async function waitForResponse(gate: ReturnType<typeof hold>, signal?: AbortSignal | null) {
  signal?.throwIfAborted();
  if (!signal) return gate.wait;
  let onAbort!: () => void;
  const cancelled = new Promise<never>((_, reject) => {
    onAbort = () => reject(signal.reason ?? new DOMException("Offline fetch cancelled", "AbortError"));
    signal.addEventListener("abort", onAbort, { once: true });
  });
  try { await Promise.race([gate.wait, cancelled]); }
  finally { signal.removeEventListener("abort", onAbort); }
}
function rawResponse(message: string, id: string): Response {
  const text = JSON.stringify({ status: "answered", message });
  const item = { type: "message", id: `${id}-message`, role: "assistant", status: "completed",
    content: [{ type: "output_text", text, annotations: [] }] };
  const events = [
    { type: "response.created", response: { id, status: "in_progress", output: [] } },
    { type: "response.output_item.added", output_index: 0, item: { ...item, status: "in_progress", content: [] } },
    { type: "response.content_part.added", output_index: 0, content_index: 0, part: { type: "output_text", text: "", annotations: [] } },
    { type: "response.output_text.delta", output_index: 0, content_index: 0, delta: text },
    { type: "response.output_item.done", output_index: 0, item },
    { type: "response.completed", response: { id, status: "completed", output: [item],
      usage: { input_tokens: 7, output_tokens: 3, total_tokens: 10 } } },
  ];
  return new Response(events.map(event => `event: ${event.type}\ndata: ${JSON.stringify(event)}\n\n`).join(""),
    { status: 200, headers: { "content-type": "text/event-stream" } });
}
async function studio(auth: "valid" | "missing" | "invalid" | "expired" = "valid", codex?: CodexFixture) {
  const root = await mkdtemp(join(tmpdir(), "inkos-studio-pi-combination-"));
  const agentDir = join(root, "isolated-pi-home");
  vi.stubEnv("PI_CODING_AGENT_DIR", agentDir);
  if (auth !== "missing") {
    await mkdir(agentDir);
    // Credential inputs are allowed native-store fixtures; owner/admission and
    // execution/history receipts are exclusively generated by production code.
    await writeFile(join(agentDir, "auth.json"), JSON.stringify({ openai: auth === "invalid"
      ? { type: "oauth", access: "synthetic-invalid-access", refresh: null, expires: "invalid" }
      : credential(auth, auth === "expired" ? 1 : Date.now() + 3_600_000) }));
    await writeFile(join(agentDir, "settings.json"), JSON.stringify({ defaultProvider: "openai", defaultModel: "gpt-5.4", defaultThinkingLevel: "low" }));
  }
  await writeFile(join(root, "inkos.json"), JSON.stringify({ name: "Offline Pi caller", version: "0.1.0", language: "en" }));
  const factory = codex?.createClient ?? (async () => { throw new Error("Codex fallback forbidden"); });
  createCodexClient.mockImplementation(factory);
  const accountService = createCodexAccountService({ projectDir: root, clientFactory: factory });
  const app = createStudioServer({} as never, root, { codexAccountService: accountService });
  const sessions = new Set<string>();
  const fixture = { root, agentDir, app, sessions, async session() {
    const response = await app.request("/api/v1/sessions", post({ sessionKind: "chat" }));
    expect(response.status, await response.clone().text()).toBe(200);
    const { session } = await response.json(); sessions.add(session.sessionId); return session.sessionId as string;
  } };
  fixtures.push(fixture);
  await saveHarness(fixture, "pi");
  return fixture;
}
async function saveHarness(fixture: { root: string; app: ReturnType<typeof createStudioServer> }, harness: "codex" | "pi") {
  const settings = await readAgentSettings(fixture.root);
  const response = await fixture.app.request("/api/v1/agent-configuration/settings", {
    ...post({ expectedRevision: settings.revision, patch: { selectedHarnessId: harness } }), method: "PUT",
  });
  expect(response.status, await response.clone().text()).toBe(200);
  return (await response.json()).settings;
}
function run(fixture: Awaited<ReturnType<typeof studio>>, sessionId: string, instruction: string): Promise<Response> {
  // app.request invokes the actual existing Hono route; global fetch below is
  // reserved exclusively for the official SDK's external native transport.
  const response = Promise.resolve(fixture.app.request("/api/v1/agent", post({ sessionId, instruction })));
  pending.push(response); return response;
}
async function history(root: string, sessionId: string) {
  const transcript = await readTranscriptEvents(root, sessionId);
  const store = new CreativeEpisodeStore(join(root, ".inkos", "harness.sqlite"));
  try {
    const episodes = store.listEpisodes(), events = episodes.flatMap(episode => store.listEvents(episode.id));
    return { transcript, episodes, events, projected: projectRunHistory({ sessionId, transcript, episodes, events }) };
  } finally { store.close(); }
}
function expectNoPrivateHistory(value: unknown) {
  const serialized = JSON.stringify(value);
  for (const privateField of ["connectionRef", "authContextRef", "synthetic-pi-access", "synthetic-pi-refresh", "fixture@example.com"])
    expect(serialized).not.toContain(privateField);
}
